"""Код платежа — то, что клиент пишет в комментарии к переводу.

Зачем он вообще нужен. Деньги приходят на карту или счёт отдельным потоком:
банк не знает ни про сделку, ни про клиента, в выписке видно только сумму,
время и комментарий. Код в комментарии — единственная нить, которая связывает
строку выписки с конкретной сделкой в CRM.

Почему не номер сделки, как было раньше:

- **Ошибка в одной цифре попадает в чужую сделку.** «137» вместо «136» — это
  валидный номер другого клиента, и оплата привяжется не туда. В коде из букв
  и цифр с проверочным символом опечатка почти всегда не проходит проверку.
- **Номер сделки — это счётчик.** Отправляя «Код платежа: 137», компания
  сообщает клиенту, сколько у неё было продаж.
- **Похожие символы путают при переписывании.** Алфавит без 0/O, 1/I/L, 5/S
  и 8/B: клиент перепечатывает код с экрана телефона, а не копирует.

Формат: `AC-XXXXXX`, где шесть символов — пять случайных плюс проверочный.
Пять символов из алфавита в 26 знаков — почти 12 миллионов вариантов: при
десятках тысяч сделок в год случайное совпадение маловероятно, а уникальность
всё равно гарантирует индекс в базе, не удача.

Старые числовые коды остаются рабочими: поиск понимает оба вида.
"""

import re
import secrets

# Алфавит без похожих начертаний: ни 0/O, ни 1/I/L, ни 5/S, ни 8/B.
ALPHABET = "ACDEFGHJKMNPQRTUVWXY234679"
PREFIX = "AC-"
BODY_LENGTH = 5


# Ищем код в произвольном тексте: клиент присылает «оплатил, AC-K7M2QP»,
# а руководитель копирует строку целиком из банковской выписки.
CODE_RE = re.compile(rf"AC[-\s]?([{ALPHABET}]{{{BODY_LENGTH + 1}}})", re.IGNORECASE)


def _checksum(body: str) -> str:
    """Проверочный символ.

    Вес символа зависит от позиции, поэтому ловится не только «не та буква»,
    но и переставленные местами соседние — вторая по частоте ошибка при
    переписывании кода с экрана.
    """
    total = sum((index + 1) * ALPHABET.index(char) for index, char in enumerate(body))
    return ALPHABET[total % len(ALPHABET)]


def generate() -> str:
    body = "".join(secrets.choice(ALPHABET) for _ in range(BODY_LENGTH))
    return f"{PREFIX}{body}{_checksum(body)}"


def normalize(raw: str) -> str:
    """Приводит то, что человек скопировал из чата или выписки, к виду кода.

    Клиенты присылают «ac-k7m2q», «AC K7M2Q», «Код платежа: AC-K7M2Q» —
    к моменту сверки это должно быть одно и то же значение.
    """
    found = CODE_RE.search(raw or "")
    if found:
        return f"{PREFIX}{found.group(1).upper()}"
    # Код без приставки: «K7M2QP» — тоже принимаем, люди её теряют.
    cleaned = "".join(ch for ch in (raw or "").upper() if ch in ALPHABET)
    if len(cleaned) == BODY_LENGTH + 1:
        return f"{PREFIX}{cleaned}"
    return ""
